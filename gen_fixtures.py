_PKA = {"ALA": 4.0, "ARG": 12.0, "ASN": 4.2, "ASP": 3.9, "CYS": 9.0,
        "GLN": 4.3, "GLU": 4.4, "GLY": 4.1, "HIS": 6.5, "ILE": 3.8,
        "LEU": 4.0, "LYS": 10.4, "MET": 4.1, "PHE": 3.9, "PRO": 4.2,
        "SER": 4.3, "THR": 4.2, "TRP": 4.0, "TYR": 10.0, "VAL": 3.9}

_FIXED = {"33": ("HIS", 6.50, 45), "34": ("HIS", 6.80, 40),
          "70": ("HIS", 6.20, 50), "25": ("CYS", 99.99, 95)}


def gen_pka() -> None:
    """130 rows; HIS 33/34/70 at pKa ~6.5 (flagged), CYS 25 at 99.99."""
    lines = ["# PROPKA synthetic fixture (gen_fixtures.py)",
             "---------  ------   ------    ------",
             "RESIDUE    NUMBER   CHAIN     pKa      buried",
             "---------  ------   ------    ------"]
    for i in range(1, 131):
        key = str(i)
        if key in _FIXED:
            res, pka, buried = _FIXED[key]
        else:
            res = AA3[(i - 1) % 20]
            pka, buried = _PKA[res], 10 + (i * 7) % 70
        lines.append(f"{res:<3s} {i:>7d}     A    {pka:7.2f}"
                     f"    {buried:>3d} %")
    lines += ["", "The pI is 6.24 for the folded protein."]
    w("propka_apo.pka", "\n".join(lines) + "\n")


