"""Generate small self-contained fixtures for the public-repo test suite.

Writes into <repo>/mcp-protein-tools/fixtures/. Files are hand-scale
synthetic inputs (a few KB each) that satisfy the assertions in
test_units.py, test_cif.py, test_phase12.py, test_phase3.py,
test_server.py, test_pdb_by_id.py, test_read_fasta.py and
test_structure_stats.py — so the public repo is genuinely self-testing
on a stranger's machine (no E:\\ paths, no 133 MB index DB).

Usage:  python gen_fixtures.py
"""
from __future__ import annotations

import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FIX = os.path.join(HERE, "fixtures")


def w(name: str, text: str) -> None:
    p = os.path.join(FIX, name)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"  wrote {name} ({os.path.getsize(p) / 1024:.1f} KB)")


AA3 = ["ALA", "ARG", "ASN", "ASP", "CYS", "GLN", "GLU", "GLY", "HIS", "ILE",
       "LEU", "LYS", "MET", "PHE", "PRO", "SER", "THR", "TRP", "TYR", "VAL"]


def pdb_atom(serial: int, name: str, res: str, chain: str, seq: int,
              x: float, y: float, z: float, el: str,
              het: bool = False, b: float = 20.0, occ: float = 1.00,
              icode: str = " ") -> str:
    rec = "HETATM" if het else "ATOM  "
    line = (f"{rec}{serial:>5d} {name:^4s} {res:>3s} {chain}{seq:>4d}"
            f"{icode}   {x:8.3f}{y:8.3f}{z:8.3f}{occ:6.2f}{b:6.2f}")
    return line.ljust(76) + f"{el:>2s}"


