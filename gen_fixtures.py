def gen_cif() -> None:
    """80-residue chain + 2 CA ions + pLDDT-like B-factors (55..97)."""
    hdr = ["data_fixture",
           "_struct.title 'synthetic Ca2 fixture for public-repo tests'",
           "loop_",
           "_atom_site.group_PDB",
           "_atom_site.id",
           "_atom_site.type_symbol",
           "_atom_site.label_atom_id",
           "_atom_site.label_comp_id",
           "_atom_site.auth_asym_id",
           "_atom_site.auth_seq_id",
           "_atom_site.pdbx_PDB_ins_code",
           "_atom_site.Cartn_x",
           "_atom_site.Cartn_y",
           "_atom_site.Cartn_z",
           "_atom_site.B_iso_or_equiv"]
    rows = []
    k = 0
    for i in range(1, 81):
        res = AA3[(i - 1) % 20]
        b = 55.0 + 42.0 * (0.5 + 0.5 * math.sin(i * 0.35))
        for an in ("N", "CA", "C", "O"):
            k += 1
            el = "N" if an == "N" else ("C" if an != "O" else "O")
            rows.append(f"ATOM {k} {el} {an} {res} A {i} ? "
                        f"{i * 3.8:.3f} 0.000 0.000 {b:.2f}")
    for j, near in enumerate((33, 70)):
        k += 1
        rows.append(f"HETATM {k} CA CA CA A {900 + j} ? "
                    f"{near * 3.8 + 1.0:.3f} 1.000 0.000 92.50")
    rows.append("#")
    w("fold_a0a977pl24_2ca2_model_0.cif", "\n".join(hdr + rows) + "\n")


def main() -> None:
    os.makedirs(FIX, exist_ok=True)
    gen_fasta()
    gen_holo()
    gen_zn()
    gen_xvgs()
    gen_pka()
    gen_cif()
    print("fixtures complete.")


if __name__ == "__main__":
    main()
